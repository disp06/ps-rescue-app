#!/usr/bin/env python3
"""Render ASCII 32..126 of a monospace TTF into a 10x20 8-bit alpha atlas
and emit app/src/font_data.h. Default font: DejaVu Sans Mono (Bitstream Vera
licence, free to embed). Usage: gen_font.py [font.ttf] [out.h]"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
OUT = sys.argv[2] if len(sys.argv) > 2 else "app/src/font_data.h"
W, H, SIZE = 10, 20, 16

font = ImageFont.truetype(TTF, SIZE)
asc, desc = font.getmetrics()
y0 = (H - (asc + desc)) // 2

rows = []
for c in range(32, 127):
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    l, t, r, b = font.getbbox(chr(c))
    x = (W - (r - l)) // 2 - l if (r - l) <= W else -l
    d.text((x, y0), chr(c), fill=255, font=font)
    rows.append(list(im.getdata()))

with open(OUT, "w") as f:
    f.write("/* generated by tools/gen_font.py from DejaVu Sans Mono - do not edit */\n")
    f.write("#pragma once\n#define FONT_W %d\n#define FONT_H %d\n" % (W, H))
    f.write("static const unsigned char font_data[95][%d] = {\n" % (W * H))
    for g in rows:
        f.write("{" + ",".join(str(v) for v in g) + "},\n")
    f.write("};\n")
print("wrote", OUT)
